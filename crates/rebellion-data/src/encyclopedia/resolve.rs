#[cfg(test)]
mod tests {
    use super::{
        encode_windows_1252_scalar, encode_windows_1252_strict, unicode_15_1_scalar_lowercase,
        ScalarLowercase,
    };

    const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
    const FNV_PRIME: u64 = 0x0000_0100_0000_01b3;

    fn hash_bytes(hash: &mut u64, bytes: &[u8]) {
        for byte in bytes {
            *hash ^= u64::from(*byte);
            *hash = hash.wrapping_mul(FNV_PRIME);
        }
    }

    #[test]
    fn pinned_unicode_15_1_scalar_lowercase_matches_the_complete_mapping_digest() {
        let mut hash = FNV_OFFSET;
        let mut changed = 0_u32;

        for codepoint in 0..=0x10ffff {
            let Some(input) = char::from_u32(codepoint) else {
                continue;
            };
            let mapping = unicode_15_1_scalar_lowercase(input);
            let (length, first, second) = match mapping {
                ScalarLowercase::One(first) => (1_u8, first, None),
                ScalarLowercase::Two(first, second) => (2_u8, first, Some(second)),
            };
            if first != input || second.is_some() {
                changed += 1;
            }

            hash_bytes(&mut hash, &codepoint.to_le_bytes());
            hash_bytes(&mut hash, &[length]);
            hash_bytes(&mut hash, &(first as u32).to_le_bytes());
            if let Some(second) = second {
                hash_bytes(&mut hash, &(second as u32).to_le_bytes());
            }
        }

        assert_eq!(changed, 1_433);
        assert_eq!(hash, 0x38be_0c77_ce83_a9a9);

        let mut scalar_lowercase = String::new();
        for scalar in "ΟΣ".chars() {
            unicode_15_1_scalar_lowercase(scalar).push_to(&mut scalar_lowercase);
        }
        assert_eq!(scalar_lowercase, "οσ");
        assert_ne!(scalar_lowercase, "ος");
    }

    #[test]
    fn strict_windows_1252_encoder_matches_the_complete_scalar_mapping_digest() {
        assert_eq!(
            encode_windows_1252_strict("A€É"),
            Some(vec![0x41, 0x80, 0xc9])
        );
        assert_eq!(encode_windows_1252_strict("AΩ"), None);

        let mut hash = FNV_OFFSET;
        let mut encoded = 0_u32;

        for codepoint in 0..=0x10ffff {
            let Some(input) = char::from_u32(codepoint) else {
                continue;
            };
            let output = encode_windows_1252_scalar(input);
            if output.is_some() {
                encoded += 1;
            }

            hash_bytes(&mut hash, &codepoint.to_le_bytes());
            match output {
                Some(byte) => hash_bytes(&mut hash, &[1, byte]),
                None => hash_bytes(&mut hash, &[0]),
            }
        }

        assert_eq!(encoded, 251);
        assert_eq!(hash, 0xd53f_ae7b_a2de_5e24);
    }
}
