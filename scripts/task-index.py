#!/usr/bin/env python3
"""Write the readable task graph pages in tasks/ from .beads/issues.jsonl.

The JSONL is the graph br keeps (agent_docs/task-graph.md); these pages are a
view of it for collaborators, regenerated after every br change and committed
with it. `--check` fails when the pages are out of date.

The repository is public. Text matching a deny pattern stops the run: the
built-in `worker_` (a private platform's agent id) and any line of the
untracked `.git/info/task-index-deny`.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
GRAPH = ROOT / ".beads/issues.jsonl"
OUT = ROOT / "tasks"
LOCAL_DENY = ROOT / ".git/info/task-index-deny"
DENY = ("worker_",)

# Each open node lands on the page of its first matching label.
PAGES = (
    ("ports.md", "Ports", ("port",), "Changing the port to match the original."),
    ("reviews.md", "Reviews", ("review",), "Rereading a question's decompiles against our own Ghidra project."),
    (
        "acceptance.md",
        "Acceptance",
        ("acceptance", "diagnose", "fixture", "capture", "verify"),
        "Comparison regions, their diagnoses and fixtures, and A0 captures.",
    ),
    ("questions.md", "Questions", ("question",), "Questions about the original, answered from the executable."),
    ("other.md", "Other", (), "Decisions, chores and unlabelled nodes."),
)
CLOSED_PAGE = "closed.md"
STATUS_ORDER = {"in_progress": 0, "open": 1, "blocked": 2, "deferred": 3, "closed": 4}
HEADER = "<!-- Generated by scripts/task-index.py from .beads/issues.jsonl. Do not edit. -->\n\n"


def load(path: Path) -> list[dict]:
    nodes = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return [node for node in nodes if node.get("status") != "tombstone"]


def deny_patterns() -> list[str]:
    patterns = list(DENY)
    if LOCAL_DENY.exists():
        patterns += [line.strip() for line in LOCAL_DENY.read_text().splitlines() if line.strip()]
    return [pattern.lower() for pattern in patterns]


def check_denied(nodes: list[dict]) -> list[str]:
    patterns = deny_patterns()
    hits = []
    for node in nodes:
        text = json.dumps(node).lower()
        hits += [f"{node['id']}: denied text" for pattern in patterns if pattern in text]
    return hits


def page_of(node: dict) -> str:
    if node["status"] == "closed":
        return CLOSED_PAGE
    if node.get("issue_type") == "epic":
        return "INDEX.md"
    labels = set(node.get("labels") or ())
    for name, _, wanted, _ in PAGES:
        if not wanted or labels & set(wanted):
            return name
    return "other.md"


def link(node_id: str, pages: dict[str, str], here: str, titles: dict[str, str] | None = None) -> str:
    page = pages.get(node_id)
    if page is None:
        return f"`{node_id}`"
    target = f"#{node_id}" if page == here else f"{page}#{node_id}"
    text = titles[node_id] if titles else node_id
    return f"[{text}]({target})"


def quote(text: str) -> str:
    return "\n".join(f"> {line}".rstrip() for line in text.strip().splitlines())


def date(stamp: str | None) -> str:
    return (stamp or "")[:10]


class Graph:
    def __init__(self, nodes: list[dict]):
        self.nodes = sorted(nodes, key=lambda n: n["id"])
        self.by_id = {n["id"]: n for n in self.nodes}
        self.pages = {n["id"]: page_of(n) for n in self.nodes}
        self.waits_on: dict[str, list[str]] = defaultdict(list)
        self.unblocks: dict[str, list[str]] = defaultdict(list)
        self.epic: dict[str, str] = {}
        self.children: dict[str, list[str]] = defaultdict(list)
        self.titles = {n["id"]: n["title"] for n in self.nodes}
        for node in self.nodes:
            for dep in node.get("dependencies") or ():
                first = dep["depends_on_id"]
                if first not in self.by_id:
                    continue
                if dep["type"] == "blocks":
                    self.waits_on[node["id"]].append(first)
                    self.unblocks[first].append(node["id"])
                elif dep["type"] == "parent-child":
                    self.epic[node["id"]] = first
                    self.children[first].append(node["id"])

    def open_blockers(self, node_id: str) -> list[str]:
        return [b for b in self.waits_on[node_id] if self.by_id[b]["status"] != "closed"]

    def ready(self) -> list[dict]:
        return [
            n
            for n in self.nodes
            if n["status"] == "open" and n.get("issue_type") != "epic" and not self.open_blockers(n["id"])
        ]


def order(nodes: list[dict]) -> list[dict]:
    return sorted(nodes, key=lambda n: (STATUS_ORDER.get(n["status"], 9), n.get("priority", 9), n["id"]))


def node_block(graph: Graph, node: dict, here: str) -> str:
    node_id = node["id"]
    facts = [f"**{node['status'].replace('_', ' ')}**", f"P{node.get('priority', '?')}"]
    labels = [label for label in node.get("labels") or () if label != "worker-ok"]
    if labels:
        facts.append(", ".join(labels))
    if node.get("assignee"):
        facts.append(f"assigned to {node['assignee']}")
    if node["status"] == "closed":
        facts.append(f"closed {date(node.get('closed_at'))}")
    else:
        facts.append(f"updated {date(node.get('updated_at'))}")
    meta = [f"`{node_id}` · " + " · ".join(facts)]
    if node_id in graph.epic:
        meta.append("Epic: " + link(graph.epic[node_id], graph.pages, here, graph.titles))
    if graph.waits_on[node_id]:
        meta.append("Waits on: " + ", ".join(link(b, graph.pages, here) for b in graph.waits_on[node_id]))
    if graph.unblocks[node_id]:
        meta.append("Unblocks: " + ", ".join(link(b, graph.pages, here) for b in graph.unblocks[node_id]))
    # Two trailing spaces: a Markdown line break between the facts.
    body = [f'<a id="{node_id}"></a>', f"### {node['title']}", "", "  \n".join(meta)]
    if node.get("description", "").strip():
        body += ["", quote(node["description"])]
    if (node.get("notes") or "").strip():
        body += ["", "**Notes**", "", quote(node["notes"])]
    if node["status"] == "closed" and (node.get("close_reason") or "").strip():
        body += ["", "**Closed:** " + node["close_reason"].strip()]
    return "\n".join(body) + "\n"


def kind_page(graph: Graph, name: str, title: str, blurb: str, nodes: list[dict]) -> str:
    parts = [HEADER, f"# {title}\n\n", f"{blurb} Back to the [index](INDEX.md).\n\n"]
    by_status = Counter(n["status"] for n in nodes)
    parts.append(", ".join(f"{count} {status.replace('_', ' ')}" for status, count in sorted(by_status.items(), key=lambda kv: STATUS_ORDER.get(kv[0], 9))) + ".\n\n")
    for node in order(nodes):
        parts.append(node_block(graph, node, name) + "\n")
    return "".join(parts)


def closed_page(graph: Graph, nodes: list[dict]) -> str:
    parts = [HEADER, "# Closed\n\n", f"{len(nodes)} closed nodes, newest first. Back to the [index](INDEX.md).\n\n"]
    for node in sorted(nodes, key=lambda n: (n.get("closed_at") or "", n["id"]), reverse=True):
        parts.append(node_block(graph, node, CLOSED_PAGE) + "\n")
    return "".join(parts)


def summary_row(graph: Graph, node: dict) -> str:
    title = node["title"].replace("|", "\\|")
    return f"| P{node.get('priority', '?')} | {link(node['id'], graph.pages, 'INDEX.md')} | {title} |"


def index_page(graph: Graph, page_nodes: dict[str, list[dict]]) -> str:
    nodes = graph.nodes
    counts = Counter(n["status"] for n in nodes)
    parts = [
        HEADER,
        "# Task Graph\n\n",
        "The work toward parity with the original game, as a dependency graph: a\n"
        "question about the original is answered before its review, the review\n"
        "before the port, and the port before the comparison it fixes can pass.\n"
        "These pages are generated from `.beads/issues.jsonl`, which the lead\n"
        "session keeps with [br](https://github.com/Dicklesworthstone/beads_rust);\n"
        "[agent_docs/task-graph.md](../agent_docs/task-graph.md) explains the node\n"
        "kinds and how work is claimed and closed.\n\n",
        f"{len(nodes)} nodes: "
        + ", ".join(f"{counts[s]} {s.replace('_', ' ')}" for s in sorted(counts, key=lambda s: STATUS_ORDER.get(s, 9)))
        + ".\n\n",
        "## Pages\n\n| Page | Open | What |\n|---|---|---|\n",
    ]
    for name, title, _, blurb in PAGES:
        parts.append(f"| [{title}]({name}) | {len(page_nodes.get(name, []))} | {blurb} |\n")
    parts.append(f"| [Closed]({CLOSED_PAGE}) | {len(page_nodes.get(CLOSED_PAGE, []))} closed | Finished work and how it closed. |\n\n")

    parts.append("## Epics\n\n")
    for epic in [n for n in nodes if n.get("issue_type") == "epic"]:
        kids = Counter(graph.by_id[c]["status"] for c in graph.children[epic["id"]])
        done = kids.get("closed", 0)
        total = sum(kids.values())
        parts.append(f'<a id="{epic["id"]}"></a>\n### {epic["title"]}\n\n')
        parts.append(f"`{epic['id']}` · **{epic['status'].replace('_', ' ')}** · {done} of {total} closed\n\n")
        if epic.get("description", "").strip():
            parts.append(quote(epic["description"]) + "\n\n")

    active = order([n for n in nodes if n["status"] == "in_progress" and n.get("issue_type") != "epic"])
    parts.append("## In progress\n\n")
    parts.append(table(graph, active) if active else "None.\n\n")
    ready = order(graph.ready())
    parts.append("## Ready\n\nOpen, not deferred, and waiting on nothing open; highest priority first.\n\n")
    parts.append(table(graph, ready) if ready else "None.\n\n")
    return "".join(parts)


def table(graph: Graph, nodes: list[dict]) -> str:
    return "| Priority | Node | Title |\n|---|---|---|\n" + "\n".join(summary_row(graph, n) for n in nodes) + "\n\n"


def render(nodes: list[dict]) -> dict[str, str]:
    graph = Graph(nodes)
    page_nodes: dict[str, list[dict]] = defaultdict(list)
    for node in graph.nodes:
        page_nodes[graph.pages[node["id"]]].append(node)
    files = {"INDEX.md": index_page(graph, page_nodes)}
    for name, title, _, blurb in PAGES:
        files[name] = kind_page(graph, name, title, blurb, page_nodes.get(name, []))
    files[CLOSED_PAGE] = closed_page(graph, page_nodes.get(CLOSED_PAGE, []))
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when tasks/ differs from the graph")
    args = parser.parse_args()

    nodes = load(GRAPH)
    denied = check_denied(nodes)
    if denied:
        print("task-index: refusing to write public pages:", *denied, sep="\n  ", file=sys.stderr)
        return 2
    files = render(nodes)
    stale = [name for name, text in files.items() if not (OUT / name).exists() or (OUT / name).read_text() != text]
    extra = sorted(p.name for p in OUT.glob("*.md") if p.name not in files) if OUT.exists() else []
    if args.check:
        if stale or extra:
            print("task-index: tasks/ is out of date:", *(stale + extra), sep="\n  ", file=sys.stderr)
            print("run scripts/task-index.py", file=sys.stderr)
            return 1
        return 0
    OUT.mkdir(exist_ok=True)
    for name in extra:
        (OUT / name).unlink()
    for name in stale:
        (OUT / name).write_text(files[name])
    print(f"task-index: {len(nodes)} nodes, wrote {len(stale)} of {len(files)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
